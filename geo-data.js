const GEO_WORLD_REGIONS = ["North America","Central America & Caribbean","South America","Europe","Africa","Middle East & Caucasus","Asia","Oceania"];
const GEO_STATE_REGIONS = ["New England","Mid-Atlantic","East North Central","West North Central","South Atlantic","East South Central","West South Central","Mountain","Pacific"];

function geoNorm(s) {
  return String(s || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "")
    .toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, " ").trim();
}
function geoAliases(item) {
  const a = [item.name, item.capital, ...(item.aliases || [])];
  return a.map(geoNorm);
}
function geoMatchName(item, guess) {
  const g = geoNorm(guess);
  if (!g) return false;
  return geoAliases(item).some(al => al === g || al.replace(/ /g, "") === g.replace(/ /g, ""));
}

const GeoData = { WORLD: GEO_WORLD, STATES: GEO_STATES, WORLD_REGIONS: GEO_WORLD_REGIONS, STATE_REGIONS: GEO_STATE_REGIONS, norm: geoNorm, matchName: geoMatchName, aliases: geoAliases };
if (typeof module !== "undefined") module.exports = GeoData;
else window.GeoData = GeoData;
